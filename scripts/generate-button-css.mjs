/**
 * Generate react/src/Button.css from tokens/tokens.json.
 *
 *   node scripts/generate-button-css.mjs
 *
 * The per-variant rules are generated rather than hand-written for one reason: CSS
 * cannot compose a custom-property name from parts. `var(--button-bg-${variant}-
 * ${state})` is not expressible, so every hierarchy x intent combination needs its
 * own literal block. Written by hand those blocks drift from the token file the
 * first time someone renames a token; generated, they cannot.
 *
 * Structural rules (layout, focus, truncation, spinner) are hand-written below and
 * pass through untouched — only the token plumbing is derived.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const ROOT = new URL("..", import.meta.url);
const tokens = JSON.parse(readFileSync(new URL("tokens/tokens.json", ROOT), "utf8"));
const button = tokens.component.button;

const HIERARCHIES = ["primary", "secondary", "tertiary", "text"];
const INTENTS = ["default", "destructive"];
const SIZES = { lg: "large", md: "medium", sm: "small" };

/** Assert the token exists before emitting a var() that would silently resolve to nothing. */
const tokenVar = (key) => {
  if (!(key in button)) throw new Error(`Missing component.button token: ${key}`);
  return `var(--button-${key})`;
};

const variantBlocks = HIERARCHIES.flatMap((hierarchy) =>
  INTENTS.map((intent) => {
    const infix = intent === "destructive" ? "destructive-" : "";
    const local = (group, state) => tokenVar(`${group}-${hierarchy}-${infix}${state}`);
    return [
      `.cosmos-button[data-variant="${hierarchy}"][data-intent="${intent}"] {`,
      `  --_bg: ${local("bg", "default")};`,
      `  --_bg-hover: ${local("bg", "hover")};`,
      `  --_bg-pressed: ${local("bg", "pressed")};`,
      `  --_bg-disabled: ${local("bg", "disabled")};`,
      `  --_label: ${local("label", "default")};`,
      `  --_label-disabled: ${local("label", "disabled")};`,
      `  --_border: ${local("border", "default")};`,
      `  --_border-hover: ${local("border", "hover")};`,
      `  --_border-pressed: ${local("border", "pressed")};`,
      `  --_border-disabled: ${local("border", "disabled")};`,
      `}`,
    ].join("\n");
  }),
).join("\n\n");

const sizeBlocks = Object.entries(SIZES)
  .map(([short, long]) =>
    [
      `.cosmos-button[data-size="${short}"] {`,
      `  min-height: ${tokenVar(`min-height-${short}`)};`,
      `  padding-inline: ${tokenVar(`padding-x-${short}`)};`,
      `  padding-block: ${tokenVar(`padding-y-${short}`)};`,
      `  gap: ${tokenVar(`gap-${short}`)};`,
      `  --_icon-size: ${tokenVar(`icon-size-${short}`)};`,
      `  font-family: var(--label-${long}-bold-font-family);`,
      `  font-weight: var(--label-${long}-bold-font-weight);`,
      `  font-size: var(--label-${long}-bold-font-size);`,
      `  line-height: var(--label-${long}-bold-line-height);`,
      `}`,
    ].join("\n"),
  )
  .join("\n\n");

const css = `/**
 * Do not edit directly, this file was generated by scripts/generate-button-css.mjs.
 *
 * Requires dist/web/tokens.css to be loaded first — every value here resolves through
 * a --button-* custom property, and there are no literal colours or pixel sizes.
 */

.cosmos-button {
  display: inline-flex;
  align-items: center;
  justify-content: center;
  box-sizing: border-box;
  position: relative;

  background: var(--_bg);
  color: var(--_label);
  border: ${tokenVar("border-width")} solid var(--_border);
  border-radius: ${tokenVar("radius")};

  /* Hug by default. Full width is the fullWidth prop, never a variant — see below. */
  width: auto;
  text-decoration: none;
  cursor: pointer;
  -webkit-appearance: none;
  appearance: none;
}

/*
 * Hover, active and focus-visible are the code half of the Figma State axis. Figma
 * carries them as design-only variants so a designer can show them in a mock; here
 * they are pseudo-classes the component owns. There is deliberately no state prop.
 */
.cosmos-button:hover:not(:disabled):not([data-loading="true"]) {
  background: var(--_bg-hover);
  border-color: var(--_border-hover);
}

.cosmos-button:active:not(:disabled):not([data-loading="true"]) {
  background: var(--_bg-pressed);
  border-color: var(--_border-pressed);
}

/*
 * outline, not padding and not a box-shadow inset. An outline is drawn outside the
 * border box and takes up no layout space, which is what keeps a full-width button
 * from shifting by the ring width when it takes focus — the same reason the Figma
 * ring is an outside-aligned stroke on an absolutely-positioned child.
 */
.cosmos-button:focus-visible {
  outline: ${tokenVar("focus-ring-width")} solid ${tokenVar("focus-ring")};
  outline-offset: ${tokenVar("focus-ring-offset")};
}

.cosmos-button:disabled {
  background: var(--_bg-disabled);
  border-color: var(--_border-disabled);
  color: var(--_label-disabled);
  cursor: not-allowed;
}

/* Maps to setting the Figma instance's horizontal resizing to Fill container. */
.cosmos-button[data-full-width="true"] {
  width: 100%;
}

.cosmos-button[data-loading="true"] {
  cursor: progress;
}

/* Single line, truncating — a button that reflows to two lines is a layout bug. */
.cosmos-button__label {
  overflow: hidden;
  text-overflow: ellipsis;
  white-space: nowrap;
}

.cosmos-button__icon {
  display: inline-flex;
  flex: none;
  width: var(--_icon-size);
  height: var(--_icon-size);
}

/* Icons inherit the label colour rather than carrying one of their own. */
.cosmos-button__icon > svg {
  width: 100%;
  height: 100%;
  fill: currentColor;
}

.cosmos-button__spinner {
  display: inline-flex;
  flex: none;
  width: var(--_icon-size);
  height: var(--_icon-size);
  animation: cosmos-button-spin 0.6s linear infinite;
}

.cosmos-button__spinner > svg {
  width: 100%;
  height: 100%;
  stroke: currentColor;
  fill: none;
}

@keyframes cosmos-button-spin {
  to {
    transform: rotate(360deg);
  }
}

@media (prefers-reduced-motion: reduce) {
  .cosmos-button__spinner {
    animation: none;
  }
}

/* ---- size axis ---------------------------------------------------------- */

${sizeBlocks}

/* ---- hierarchy x intent ------------------------------------------------- */

${variantBlocks}
`;

mkdirSync(new URL("react/src/", ROOT), { recursive: true });
writeFileSync(new URL("react/src/Button.css", ROOT), css);

console.log(
  `react/src/Button.css  ${HIERARCHIES.length * INTENTS.length} variant blocks, ${Object.keys(SIZES).length} size blocks`,
);
