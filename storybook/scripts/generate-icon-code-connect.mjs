// Writes one Code Connect template per Figma `Icon / *` component that the React Icon can draw.
// The Button template reads each icon's `metadata.props.name` to fill leadingIcon and trailingIcon.
// Re-run after adding a glyph to Icon/paths.ts or a component to the Figma Icons page (645:2):
//   node scripts/generate-icon-code-connect.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const FILE_URL = "https://www.figma.com/design/byPBTSedTYOO0AYwmIlncH/Cosmos";

// Figma component node IDs on the Icons page, keyed by the name after "Icon / ".
const FIGMA_ICONS = {
  "chevron-right": "55:5",
  "arrow-right": "55:8",
  plus: "55:11",
  check: "55:14",
  close: "55:17",
  spinner: "55:18",
  minus: "420:66",
  "chevron-down": "557:61",
  info: "635:120",
  "check-circle": "635:123",
  "alert-triangle": "635:126",
  "alert-circle": "635:129",
  bell: "685:28",
  flight: "685:31",
  hotel: "685:34",
  homestay: "685:37",
  train: "685:40",
  bus: "685:43",
  person: "713:26",
  list: "767:26",
  map: "767:30",
  share: "780:28",
  bookmark: "780:31",
  delete: "780:34",
  edit: "780:37",
  "content-copy": "780:40",
  "drive-file-move": "780:43",
  "auto-awesome": "876:28",
  "arrow-back": "906:28",
  "chevron-left": "906:31",
  favorite: "906:34",
  "more-horiz": "906:37",
  "more-vert": "906:40",
  search: "906:43",
};

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const iconDir = join(root, "src/components/Icon");
const outDir = join(iconDir, "code-connect");

// Only connect glyphs the React Icon knows, so every snippet compiles.
const paths = readFileSync(process.env.ICON_PATHS_FILE ?? join(iconDir, "paths.ts"), "utf8");
const codeNames = new Set([...paths.matchAll(/^ {2}"?([a-z0-9-]+)"?:/gm)].map((m) => m[1]));

mkdirSync(outDir, { recursive: true });
for (const f of readdirSync(outDir)) if (f.endsWith(".figma.ts")) rmSync(join(outDir, f));

const connected = [];
for (const [name, nodeId] of Object.entries(FIGMA_ICONS)) {
  if (!codeNames.has(name)) continue;
  writeFileSync(
    join(outDir, `${name}.figma.ts`),
    `// url=${FILE_URL}?node-id=${nodeId.replace(":", "-")}
// source=https://github.com/ivineel11/mmt-cosmos-design-tokens/blob/main/storybook/src/components/Icon/Icon.tsx
// component=Icon
// Generated by storybook/scripts/generate-icon-code-connect.mjs. Do not edit by hand.
import figma from "figma";

export default {
  example: figma.tsx\`<Icon name="${name}" />\`,
  imports: ['import { Icon } from "@mmt/cosmos"'],
  id: "icon-${name}",
  metadata: { nestable: true, props: { name: "${name}" } },
};
`,
  );
  connected.push(name);
}

const skipped = Object.keys(FIGMA_ICONS).filter((n) => !codeNames.has(n));
console.log(`Wrote ${connected.length} icon templates to ${outDir}`);
if (skipped.length) console.log(`Not in Icon/paths.ts yet, skipped: ${skipped.join(", ")}`);
